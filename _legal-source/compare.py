"""Compare privacy.md and terms.md with the 37signals originals in this folder.

Run from the repo root: python3 _legal-source/compare.py > _legal-source/COMPARISON.md
Each sentence on our pages is matched to its closest 37signals sentence:
  T = template (near-verbatim, ratio >= 0.85), A = adapted (0.6-0.85), N = new to Nomi.
"""
import collections, difflib, glob, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def clean(text):
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[*_`>#|]", " ", text)


def sentences(text):
    text = re.sub(r"^---.*?---", "", text, flags=re.S)
    out, sec = [], ""
    for line in text.splitlines():
        if line.startswith("## "):
            sec = line[3:].strip()
            continue
        if line.startswith("#"):
            continue
        for s in re.split(r"(?<=[.!?])\s+", clean(line)):
            s = " ".join(s.split()).lstrip("0123456789. -")
            if len(s.split()) >= 4:
                out.append((sec or "Introduction", s))
    return out


template = []
for path in sorted(glob.glob(os.path.join(HERE, "37signals", "*.md"))):
    if not path.endswith("LICENSE.md"):
        template += [s for _, s in sentences(open(path, encoding="utf-8").read())]
lowered = [s.lower() for s in template]

print("# How our legal pages compare with the 37signals template\n")
print("Generated by `compare.py`. T = template (near-verbatim, name swaps), A = adapted from a template sentence, N = new to Nomi.\n")
for page in ["terms", "privacy"]:
    rows = []
    for sec, s in sentences(open(os.path.join(ROOT, page + ".md"), encoding="utf-8").read()):
        match = difflib.get_close_matches(s.lower(), lowered, n=1, cutoff=0.0)
        idx = lowered.index(match[0]) if match else -1
        ratio = difflib.SequenceMatcher(None, s.lower(), match[0]).ratio() if match else 0.0
        kind = "T" if ratio >= 0.85 else "A" if ratio >= 0.6 else "N"
        rows.append((sec, s, kind, template[idx] if idx >= 0 else ""))
    total = collections.Counter()
    by_sec = collections.OrderedDict()
    for sec, s, kind, _ in rows:
        words = len(s.split())
        total[kind] += words
        by_sec.setdefault(sec, collections.Counter())[kind] += words
    n = sum(total.values())
    pct = lambda c, k: round(100 * c[k] / max(1, sum(c.values())))
    print(f"## {page}.md\n")
    print(f"{n} words: **{pct(total, 'T') + pct(total, 'A')}% from the template** ({pct(total, 'T')}% near-verbatim, {pct(total, 'A')}% adapted), {pct(total, 'N')}% new.\n")
    print("| Section | Words | Template | Adapted | New |\n|---|---:|---:|---:|---:|")
    for sec, c in by_sec.items():
        print(f"| {sec} | {sum(c.values())} | {pct(c, 'T')}% | {pct(c, 'A')}% | {pct(c, 'N')}% |")
    print("\n<details><summary>Sentence by sentence</summary>\n")
    current = None
    for sec, s, kind, src in rows:
        if sec != current:
            print(f"\n**{sec}**\n")
            current = sec
        print(f"- `{kind}` {s}")
        if kind == "A":
            print(f"  - 37signals: {src}")
    print("\n</details>\n")
